const lengths = (from: number, to: number, stepPrice: number, unavailable: number[] = []): ProductOption => {
  const values: OptionValue[] = [];
  for (let l = from, i = 0; l <= to; l += 2, i++) {
    values.push({ value: String(l), label: `${l}"`, priceDelta: i * stepPrice, unavailable: unavailable.includes(l) });
  }
  return { key: 'length', label: 'Longueur', values };
};

